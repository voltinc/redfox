import { Router } from 'express';
import { db, nowIso, projectDb } from '../db.js';
import { requireAuth, workspaceContext, audit } from '../auth.js';
import { asyncRoute, bad, notFound, requireFields } from '../util.js';
import { id } from '../crypto.js';
import { providerInfo, complete } from '../services/llm.js';
import { analyzeDeployment, analyzeText, describeSchema, generateSql, diagnoseProject } from '../services/analysis.js';

const router = Router();
router.use(requireAuth, workspaceContext);

const SUGGESTIONS = [
  { label: 'Why did the last deployment fail?', prompt: 'Why did the last deployment fail?' },
  { label: 'Explain this project schema', prompt: 'Explain the database schema for this project.' },
  { label: 'Write a query for recent rows', prompt: 'Write a SQL query that returns the 20 most recent rows of the busiest table.' },
  { label: 'Review my project configuration', prompt: 'Review my project configuration and flag anything risky.' },
];

router.get('/solene/status', asyncRoute(async (req, res) => {
  const info = providerInfo();
  res.json({
    mode: info.configured ? 'model' : 'local',
    provider: info,
    suggestions: SUGGESTIONS,
    detail: info.configured
      ? `Answers are generated by ${info.label} (${info.model}) with your workspace data as context.`
      : 'No model provider is connected. Solene answers with the local analysis engine, which reads your real deployment logs, schema and configuration. Answers are deterministic and labelled as local analysis.',
  });
}));

router.get('/solene/conversations', asyncRoute(async (req, res) => {
  const items = db.prepare(`SELECT c.*, p.name AS project_name, p.slug AS project_slug,
      (SELECT count(*) FROM messages m WHERE m.conversation_id = c.id) AS message_count
    FROM conversations c LEFT JOIN projects p ON p.id = c.project_id
    WHERE c.workspace_id = ? AND c.user_id = ? ORDER BY c.updated_at DESC LIMIT 50`).all(req.workspace.id, req.user.id);
  const projects = db.prepare('SELECT id, name, slug FROM projects WHERE workspace_id = ? ORDER BY name').all(req.workspace.id);
  res.json({ conversations: items, projects });
}));

router.post('/solene/conversations', asyncRoute(async (req, res) => {
  const { project_id, title } = req.body || {};
  let projectId = null;
  if (project_id) {
    const project = db.prepare('SELECT id FROM projects WHERE workspace_id = ? AND (id = ? OR slug = ?)')
      .get(req.workspace.id, project_id, project_id);
    if (!project) throw bad('Project not found');
    projectId = project.id;
  }
  const convId = id('cnv');
  db.prepare('INSERT INTO conversations (id, workspace_id, user_id, project_id, title, created_at, updated_at) VALUES (?,?,?,?,?,?,?)')
    .run(convId, req.workspace.id, req.user.id, projectId, title || 'New conversation', nowIso(), nowIso());
  res.status(201).json({ conversation: db.prepare('SELECT * FROM conversations WHERE id = ?').get(convId) });
}));

router.get('/solene/conversations/:conversationId', asyncRoute(async (req, res) => {
  const conversation = db.prepare('SELECT * FROM conversations WHERE id = ? AND user_id = ?')
    .get(req.params.conversationId, req.user.id);
  if (!conversation) throw notFound('Conversation not found');
  const messages = db.prepare('SELECT * FROM messages WHERE conversation_id = ? ORDER BY created_at ASC').all(conversation.id)
    .map((m) => ({ ...m, meta: m.meta ? JSON.parse(m.meta) : null }));
  const project = conversation.project_id
    ? db.prepare('SELECT id, name, slug FROM projects WHERE id = ?').get(conversation.project_id)
    : null;
  res.json({ conversation, messages, project, status: providerInfo() });
}));

router.delete('/solene/conversations/:conversationId', asyncRoute(async (req, res) => {
  const conversation = db.prepare('SELECT * FROM conversations WHERE id = ? AND user_id = ?')
    .get(req.params.conversationId, req.user.id);
  if (!conversation) throw notFound('Conversation not found');
  db.prepare('DELETE FROM conversations WHERE id = ?').run(conversation.id);
  res.json({ ok: true });
}));

/* ------------------------------------------------------------- local answers */
function projectContext(project) {
  const repo = db.prepare('SELECT * FROM repositories WHERE project_id = ?').get(project.id);
  const deployments = db.prepare('SELECT * FROM deployments WHERE project_id = ? ORDER BY created_at DESC LIMIT 5').all(project.id);
  const domains = db.prepare('SELECT hostname, status, last_error FROM domains WHERE project_id = ?').all(project.id);
  const envKeys = db.prepare('SELECT key, target, is_secret FROM env_vars WHERE project_id = ?').all(project.id);
  let schema = null;
  try {
    schema = describeSchema(projectDb(project.id), project);
  } catch { /* no db */ }
  return { repo, deployments, domains, envKeys, schema };
}

function fenced(code, lang = '') {
  return `\n\`\`\`${lang}\n${code}\n\`\`\`\n`;
}

function localAnswer(prompt, project) {
  const text = String(prompt).toLowerCase();
  const lines = [];
  const ctx = project ? projectContext(project) : null;

  lines.push(`_Local analysis · no model provider connected. This answer is computed from your workspace data._`);

  if (ctx && /deploy|build|fail|error|log|broke/.test(text)) {
    const failed = db.prepare(`SELECT id FROM deployments WHERE project_id = ? AND status = 'failed' ORDER BY created_at DESC LIMIT 1`).get(project.id);
    const target = /dpl_|deployment/.test(text)
      ? db.prepare(`SELECT id FROM deployments WHERE project_id = ? ORDER BY created_at DESC LIMIT 1`).get(project.id)
      : failed;
    if (target) {
      const analysis = analyzeDeployment(target.id);
      lines.push(`\n**${analysis.project.name} · ${analysis.deployment.environment} · ${analysis.deployment.commit?.slice(0, 7)}**\n`);
      lines.push(analysis.summary);
      if (analysis.evidence.length) {
        lines.push('\n**Error lines**');
        for (const e of analysis.evidence) lines.push(`- \`${e.phase}\` ${e.message}`);
      }
      if (analysis.causes.length) {
        lines.push('\n**Likely cause**');
        for (const c of analysis.causes) lines.push(`- ${c.cause}`);
      }
      lines.push('\n**What to change**');
      for (const fix of analysis.fixes) lines.push(`- ${fix}`);
      lines.push(`\nConfidence: ${analysis.confidence} (${analysis.error_lines} error lines of ${analysis.log_lines}).`);
    } else {
      lines.push('\nThere are no failed deployments recorded for this project, so there is nothing to diagnose.');
      const ready = ctx.deployments.find((d) => d.status === 'ready');
      if (ready) lines.push(`The most recent ready deployment is ${ready.commit_sha?.slice(0, 7)} on ${ready.environment}.`);
    }
  } else if (ctx && /sql|query|select|insert|update/.test(text)) {
    const generated = generateSql(projectDb(project.id), project, prompt);
    lines.push(`\n${generated.explanation}\n`);
    lines.push(fenced(generated.sql, 'sql'));
    lines.push(`Run it in the SQL editor with read mode first. Writes need the run mode switched to write.`);
  } else if (ctx && /schema|table|column|database|data model/.test(text)) {
    if (ctx.schema) {
      lines.push(`\n${ctx.schema.markdown}\n`);
      lines.push(`Each project gets its own database file, so a query in this project cannot read another project's tables.`);
    } else {
      lines.push('\nThis project has no database yet.');
    }
  } else if (ctx && /domain|dns|ssl|cert/.test(text)) {
    if (ctx.domains.length) {
      lines.push('\n**Domains**');
      for (const d of ctx.domains) lines.push(`- \`${d.hostname}\` is ${d.status}${d.last_error ? `: ${d.last_error}` : ''}`);
      lines.push('\nPoint a CNAME at `cname.redfox.app` and add the TXT record shown on the Domains page, then run Verify. Verification performs a real DNS lookup.');
    } else {
      lines.push('\nNo custom domains are attached to this project. Add one from Project settings → Domains.');
    }
  } else if (ctx && /env|secret|variable|key/.test(text)) {
    lines.push('\n**Environment variables (names only)**');
    if (ctx.envKeys.length) {
      for (const v of ctx.envKeys) lines.push(`- \`${v.key}\` → ${v.target}${v.is_secret ? ' (secret)' : ''}`);
      lines.push('\nValues are encrypted at rest and never returned to the browser unmasked. Builds receive only the variables scoped to their environment.');
    } else {
      lines.push('- none configured');
    }
  } else if (ctx && /config|setting|review|risk|improve|performance/.test(text)) {
    const findings = diagnoseProject(project);
    lines.push(`\n**${project.name} configuration review**`);
    lines.push(fenced(`framework    ${project.framework}\nrunner       ${project.runner}\ninstall      ${project.install_command}\nbuild        ${project.build_command}\noutput       ${project.output_dir}\nproduction   ${project.production_branch}`));
    for (const f of findings) lines.push(`- ${f.level === 'warn' ? '**Warning**' : f.level === 'ok' ? '**OK**' : 'Info'}: ${f.message}`);
    if (ctx.deployments.filter((d) => d.status === 'failed').length >= 2) {
      lines.push('- **Warning**: repeated failures on the same project usually mean the build command or output directory no longer matches the repository.');
    }
  } else if (ctx) {
    lines.push(`\n**${project.name}** (\`${project.slug}\`) is a ${project.framework} project using the ${project.runner} runner.`);
    lines.push(`- Repository: ${ctx.repo ? `\`${ctx.repo.slug}\`` : 'not connected'}`);
    lines.push(`- Build: \`${project.install_command} && ${project.build_command}\` → \`${project.output_dir}\``);
    lines.push(`- Recent deployments: ${ctx.deployments.map((d) => `${d.status}`).join(', ') || 'none'}`);
    if (ctx.schema) lines.push(`- Database: ${ctx.schema.tables.length} tables`);
    lines.push('\nAsk about a deployment, the schema, environment variables, domains or your build configuration and I will work from the real records.');
  } else {
    lines.push('\nSelect a project in the context selector, then ask about deployments, the database schema, environment variables, domains or configuration. I read the real records for whichever project you pick.');
    const failures = db.prepare(`SELECT d.id, d.error, p.name FROM deployments d JOIN projects p ON p.id = d.project_id
      WHERE d.workspace_id = ? AND d.status = 'failed' ORDER BY d.created_at DESC LIMIT 3`).all(...[]);
    void failures;
  }

  const patterns = [];
  if (ctx) {
    const failed = db.prepare(`SELECT id FROM deployments WHERE project_id = ? AND status = 'failed' ORDER BY created_at DESC LIMIT 1`).get(project.id);
    if (failed) {
      const logs = db.prepare("SELECT message FROM deployment_logs WHERE deployment_id = ? AND level = 'error'").all(failed.id);
      patterns.push(...analyzeText(logs.map((l) => l.message).join('\n')));
    }
  }
  if (patterns.length && !ctx) {
    lines.push('\n**Patterns detected in recent failed builds**');
    for (const p of patterns.slice(0, 2)) lines.push(`- ${p.cause}`);
  }

  return lines.join('\n');
}

function systemPrompt(project, ctx) {
  return [
    'You are Solene, the AI development assistant inside Redfox, a developer platform for git, deployments, databases, storage and infrastructure.',
    'Answer as a senior platform engineer: concrete, specific, no filler. Use Markdown with short sections and fenced code blocks where useful.',
    'Only state facts that come from the context below. If the context does not contain the answer, say what you would need to check and where in Redfox to look.',
    project ? `Active project: ${project.name} (${project.slug}), framework ${project.framework}, runner ${project.runner}.` : 'No project is selected.',
    ctx ? `Project configuration: install="${project.install_command}", build="${project.build_command}", output="${project.output_dir}", production branch="${project.production_branch}".` : '',
    ctx?.repo ? `Repository: ${ctx.repo.slug} (${ctx.repo.default_branch}).` : '',
    ctx ? `Recent deployments: ${ctx.deployments.map((d) => `${d.environment}:${d.status}:${d.commit_sha?.slice(0, 7)}`).join(', ') || 'none'}.` : '',
    ctx?.schema ? `Database tables: ${ctx.schema.tables.map((t) => `${t.name}(${t.rows})`).join(', ')}.` : '',
    ctx ? `Environment variable keys: ${ctx.envKeys.map((e) => e.key).join(', ') || 'none'}.` : '',
    ctx ? `Domains: ${ctx.domains.map((d) => `${d.hostname}:${d.status}`).join(', ') || 'none'}.` : '',
  ].filter(Boolean).join('\n');
}

router.post('/solene/conversations/:conversationId/messages', asyncRoute(async (req, res) => {
  const conversation = db.prepare('SELECT * FROM conversations WHERE id = ? AND user_id = ?')
    .get(req.params.conversationId, req.user.id);
  if (!conversation) throw notFound('Conversation not found');
  const { content, project_id } = req.body || {};
  requireFields(req.body || {}, ['content']);

  if (project_id !== undefined) {
    const project = project_id
      ? db.prepare('SELECT id FROM projects WHERE workspace_id = ? AND (id = ? OR slug = ?)').get(req.workspace.id, project_id, project_id)
      : null;
    if (project_id && !project) throw bad('Project not found');
    conversation.project_id = project?.id ?? null;
    db.prepare('UPDATE conversations SET project_id = ? WHERE id = ?').run(conversation.project_id, conversation.id);
  }

  const project = conversation.project_id
    ? db.prepare('SELECT * FROM projects WHERE id = ?').get(conversation.project_id)
    : null;

  db.prepare('INSERT INTO messages (id, conversation_id, role, content, created_at) VALUES (?,?,?,?,?)')
    .run(id('msg'), conversation.id, 'user', String(content).slice(0, 8000), nowIso());

  if (conversation.title === 'New conversation') {
    db.prepare('UPDATE conversations SET title = ? WHERE id = ?').run(String(content).slice(0, 60), conversation.id);
  }

  const info = providerInfo();
  let answer;
  let meta;
  if (info.configured) {
    const history = db.prepare('SELECT role, content FROM messages WHERE conversation_id = ? ORDER BY created_at ASC LIMIT 20').all(conversation.id);
    const ctx = project ? projectContext(project) : null;
    try {
      answer = await complete({ system: systemPrompt(project, ctx), messages: history });
      meta = { source: 'model', provider: info.provider, model: info.model };
    } catch (error) {
      answer = `The model provider failed to answer: ${error.message}\n\n${project ? localAnswer(content, project) : localAnswer(content, null)}`;
      meta = { source: 'local', fallback: true, error: error.message };
    }
  } else {
    answer = localAnswer(content, project);
    meta = { source: 'local', engine: 'redfox-analysis-v1' };
  }

  const messageId = id('msg');
  db.prepare('INSERT INTO messages (id, conversation_id, role, content, meta, created_at) VALUES (?,?,?,?,?,?)')
    .run(messageId, conversation.id, 'assistant', answer, JSON.stringify(meta), nowIso());
  db.prepare('UPDATE conversations SET updated_at = ? WHERE id = ?').run(nowIso(), conversation.id);

  res.status(201).json({
    message: { ...db.prepare('SELECT * FROM messages WHERE id = ?').get(messageId), meta },
    mode: meta.source,
    provider: info,
  });
}));

router.post('/solene/analyze-deployment/:deploymentId', asyncRoute(async (req, res) => {
  const deployment = db.prepare('SELECT id FROM deployments WHERE id = ? AND workspace_id = ?')
    .get(req.params.deploymentId, req.workspace.id);
  if (!deployment) throw notFound('Deployment not found');
  const analysis = analyzeDeployment(deployment.id);
  audit(req.workspace.id, analysis.project.id, 'solene', `Deployment analysis requested for ${deployment.id}`, req.user.name);
  res.json({ analysis, mode: 'local' });
}));

